export function getCropById(id: string): Crop | undefined {
  return CROPS.find(c => c.id === id);
}

export function getCropsByIds(ids: string[]): Crop[] {
  return ids.map(id => getCropById(id)).filter(Boolean) as Crop[];
}

export function searchCrops(query: string): Crop[] {
  const q = query.toLowerCase().trim();
  if (!q) return CROPS;
  return CROPS.filter(c =>
    c.name.toLowerCase().includes(q) ||
    Object.values(c.localNames).some(n => n.toLowerCase().includes(q)) ||
    c.category.includes(q)
  );
}
