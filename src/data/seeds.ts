export function searchSeedVarieties(query: string, season?: string, cropId?: string): SeedVariety[] {
  const q = query.toLowerCase().trim();
  return SEED_VARIETIES.filter(s => {
    const matchesQuery =
      !q ||
      s.varietyName.toLowerCase().includes(q) ||
      s.cropName.toLowerCase().includes(q) ||
      s.soilSuitability.some(soil => soil.toLowerCase().includes(q)) ||
      s.pestDiseaseResistance.some(p => p.toLowerCase().includes(q));
    const matchesSeason = !season || s.recommendedSeason.includes(season as any);
    const matchesCrop = !cropId || s.cropId === cropId;
    return matchesQuery && matchesSeason && matchesCrop;
  });
}
