export function searchSchemes(query: string, level?: string, category?: string, state?: string): Scheme[] {
  const q = query.toLowerCase().trim();
  return SCHEMES.filter(s => {
    const matchesQuery = !q || s.name.toLowerCase().includes(q) || s.shortDescription.toLowerCase().includes(q);
    const matchesLevel = !level || s.level === level;
    const matchesCategory = !category || s.category === category;
    const matchesState = !state || s.stateApplicability.length === 0 || s.stateApplicability.includes(state);
    return matchesQuery && matchesLevel && matchesCategory && matchesState;
  });
}
