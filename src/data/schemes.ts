export function searchSchemes(
  query: string,
  level?: string,
  category?: string,
  state?: string
): Scheme[] {
  const q = query.toLowerCase().trim();
  return SCHEMES.filter(s => {
    const matchesQuery =
      !q ||
      s.name.toLowerCase().includes(q) ||
      s.code.toLowerCase().includes(q) ||
      s.shortDescription.toLowerCase().includes(q) ||
      s.category.toLowerCase().includes(q) ||
      s.implementingDepartment.toLowerCase().includes(q) ||
      (s.benefits && s.benefits.toLowerCase().includes(q)) ||
      (s.keyFeatures && s.keyFeatures.some(f => f.toLowerCase().includes(q))) ||
      (s.beneficiaryCategories && s.beneficiaryCategories.some(b => b.toLowerCase().includes(q)));
    const matchesLevel = !level || s.level === level;
    const matchesCategory = !category || s.category === category;
    const matchesState =
      !state ||
      s.stateApplicability.length === 0 ||
      s.stateApplicability.includes(state);
    return matchesQuery && matchesLevel && matchesCategory && matchesState;
  });
}

export function getSchemeById(id: string): Scheme | undefined {
  return SCHEMES.find(s => s.id === id || s.code.toLowerCase() === id.toLowerCase());
}
