export function searchDbtRecords(query: string, schemeCode?: string, state?: string): DbtRecord[] {
  const q = query.toLowerCase().trim();
  return DBT_RECORDS.filter(r => {
    const matchesQuery =
      !q ||
      r.farmerName.toLowerCase().includes(q) ||
      r.village.toLowerCase().includes(q) ||
      r.district.toLowerCase().includes(q) ||
      r.utrNumber.toLowerCase().includes(q) ||
      r.bankName.toLowerCase().includes(q);
    const matchesScheme = !schemeCode || r.schemeCode === schemeCode;
    const matchesState = !state || r.state === state;
    return matchesQuery && matchesScheme && matchesState;
  });
}
